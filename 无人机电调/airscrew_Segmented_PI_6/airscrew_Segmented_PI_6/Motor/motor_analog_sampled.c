void motor_volt_bus(void)
{
    analog.volt_bus = (float)(VOLT_BUS_REGISTER * VBUS_CONVERSION_FACTOR);   //�õ�ĸ�ߵ�ѹ
		analog.volt_filter = analog.filterK1 * analog.volt_filter + analog.filterK2 * analog.volt_bus;
	
}

 

void motor_volt_temp_filter_init(void)
{
		analog.filterK1 = 1.0f/( 1 + 0.001f*2*PI*30 );		/* Low-pass cut-off frequency = 30 Hz, systick sample period is 1ms */
		analog.filterK2 = 1.0f - analog.filterK1;
		analog.volt_filter = 0;
		analog.temp_filter = 0;
}

 



